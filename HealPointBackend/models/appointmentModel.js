import mongoose from "mongoose";

const appointmentSchema = new mongoose.Schema(
  {
    appointmentId: { type: String, unique: true },
    displayAppointmentId: { type: String },
    userId: { type: mongoose.Schema.Types.ObjectId, ref: "User", required: true },
    doctorId: { type: mongoose.Schema.Types.ObjectId, ref: "Doctor", required: true },
    hospitalId: { type: mongoose.Schema.Types.ObjectId, ref: "Hospital", required: true },
    hospitalName: { type: String, default: "" },
    slotDate: { type: String, required: true },
    slotTime: { type: String, required: true },
    patientName: { type: String, required: true },
    patientPhone: { type: String, default: "" },
    familyMemberId: { type: mongoose.Schema.Types.ObjectId },
    familyRelationship: { type: String, default: "Self" },
    isFamilyBooking: { type: Boolean, default: false },
    amount: { type: Number, default: 0 },
    billing: {
      consultationFee: { type: Number, default: 0 },
      serviceFee: { type: Number, default: 0 },
      platformFee: { type: Number, default: 0 },
      discount: { type: Number, default: 0 },
      subscriptionBenefit: { type: Number, default: 0 },
      planApplied: { type: String, default: "free" },
      planName: { type: String, default: "Free" },
      subtotal: { type: Number, default: 0 },
      totalAmount: { type: Number, default: 0 },
    },
    consultationType: { type: String, enum: ["clinic", "video"], default: "clinic" },
    consultationMode: { type: String, enum: ["scheduled", "instant"], default: "scheduled" },
    meetingUrl: { type: String, default: "" },
    meetingStatus: { type: String, enum: ["not_created", "ready", "started", "completed"], default: "not_created" },
    consultationStatus: {
      type: String,
      enum: ["waiting", "doctor_ready", "ready_to_join", "in_progress", "completed", "unavailable"],
      default: "waiting",
    },
    status: {
      type: String,
      enum: ["pending", "confirmed", "completed", "cancel", "rescheduled", "missed"],
      default: "pending",
    },
    payment: { type: Boolean, default: false },
    paymentMethod: { type: String, enum: ["cash", "online"], default: "cash" },
    paymentStatus: { type: String, enum: ["PENDING", "SUCCESS", "FAILED", "CANCELLED", "REFUNDED"], default: "PENDING" },
    razorpayOrderId: { type: String, default: "" },
    razorpayPaymentId: { type: String, default: "" },
    diagnosis: { type: String, default: "" },
    prescription: { type: String, default: "" },
    medicines: [
      {
        name: { type: String, required: true },
        dosage: { type: String, default: "" },
        frequency: { type: String, default: "" },
        duration: { type: String, default: "" },
        instructions: { type: String, default: "" },
      },
    ],
    medicalNotes: { type: String, default: "" },
    followUpAdvice: { type: String, default: "" },
    medicalReports: [
      {
        name: { type: String, required: true },
        url: { type: String, required: true },
        type: { type: String, default: "application/pdf" },
        uploadedAt: { type: Date, default: Date.now },
      },
    ],
    isReviewed: { type: Boolean, default: false },
    reviewId: { type: mongoose.Schema.Types.ObjectId, ref: "Review" },
    checkedIn: { type: Boolean, default: false },
    checkInAt: { type: Date },
    queueToken: { type: String, default: "" },
    queueStatus: {
      type: String,
      enum: ["not_checked_in", "waiting", "called", "in_consultation", "completed", "cancelled"],
      default: "not_checked_in",
    },
    calledAt: { type: Date },
    consultationStartedAt: { type: Date },
    consultationEndedAt: { type: Date },
    estimatedWaitMinutes: { type: Number, default: 0 },
    vitals: {
      bloodPressure: { type: String, default: "" },
      heartRate: { type: Number },
      temperature: { type: Number },
      spO2: { type: Number },
      weight: { type: Number },
    },
    reminder24hSent: { type: Boolean, default: false },
    reminder24hSentAt: { type: Date },
    reminder1hSent: { type: Boolean, default: false },
    reminder1hSentAt: { type: Date },
    reminderLogs: [
      {
        type: { type: String },
        status: { type: String },
        sentAt: { type: Date, default: Date.now },
        recipient: { type: String },
        error: { type: String },
      },
    ],
  },
  { timestamps: true }
);

export default mongoose.models.Appointment || mongoose.model("Appointment", appointmentSchema);
